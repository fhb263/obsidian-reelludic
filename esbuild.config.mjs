import esbuild from 'esbuild'
import process from 'process'
import fs from 'fs'
import builtins from 'builtin-modules'
import esbuildSvelte from 'esbuild-svelte'
import sveltePreprocess from 'svelte-preprocess'

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`

// 2026-10-22：PDF 不再打包 pdfjs —— 原先这里有个 `pdfWorkerInline` 插件，
// 把 pdfjs-dist 的 pdf.worker.min.mjs 读成字符串塞进产物、再用 Blob URL 当 workerSrc。
// 现在渲染统一复用 Obsidian 自带的 pdfjs（`loadPdfJs()` → /lib/pdfjs/*，见 src/modals/PdfReaderModal.ts），
// 产物因此少了约 1.3MB，也消除了「自带 v4 覆盖掉引擎 v5 全局」的冲突。⛔ 别再把它加回来。

// Bases 配套 CSS 片段内联：样式源文件 `docs/ReelLudic Bases 样式.css` 以字符串注入虚拟模块
// `reelludic:bases-css`，供 main.ts 生成时写进 `.obsidian/snippets/`。
// ⚠️ 这样产物体积只增加几 KB，但单文件三件套的发布形态不变（不需要多发一个数据文件）；
//    ⛔ tsc 不认识这个虚拟模块，声明在 `src/types/bases-css.d.ts` —— 改模块名要同步改那里。
const basesSnippetInline = {
    name: 'bases-snippet-inline',
    setup(build) {
        build.onResolve({ filter: /^reelludic:bases-css$/ }, () => {
            return { path: 'bases-css', namespace: 'bases-snippet' };
        });
        build.onLoad({ filter: /.*/, namespace: 'bases-snippet' }, () => {
            const cssPath = new URL('./docs/ReelLudic Bases 样式.css', import.meta.url);
            const code = fs.readFileSync(cssPath, 'utf8');
            return {
                contents: `const _css = ${JSON.stringify(code)};\nexport default _css;`,
                loader: 'js',
            };
        });
    },
}

const prod = process.argv[2] === 'production'

const context = await esbuild.context({
    banner: {
        js: banner,
    },
    entryPoints: ['main.ts'],
    bundle: true,
    plugins: [
        basesSnippetInline,
        esbuildSvelte({
            compilerOptions: { css: 'injected' },
            preprocess: sveltePreprocess(),
            onwarn: (warning, handler) => {
                // 忽略 a11y 告警（Obsidian 插件表单控件，非公开网页；label 关联后续完善）
                if (warning.code && String(warning.code).startsWith('a11y-')) return;
                handler(warning);
            },
        }),
    ],
    external: [
        'obsidian',
        'electron',
        '@codemirror/autocomplete',
        '@codemirror/collab',
        '@codemirror/commands',
        '@codemirror/language',
        '@codemirror/lint',
        '@codemirror/search',
        '@codemirror/state',
        '@codemirror/view',
        '@lezer/common',
        '@lezer/highlight',
        '@lezer/lr',
        ...builtins,
    ],
    format: 'cjs',
    target: 'es2018',
    // 构建标识（#334）：把**打包时刻**注入 `__REEL_BUILD__`，插件启动时打印一行。
    // 专治「重载了没有」这个反复出现的排查盲区 —— 磁盘上的 main.js 是新的、而 Obsidian 内存里
    // 跑的仍是旧代码时，症状会表现成「刚修的问题又出现了」，此前只能靠反推代码里的字符串来判断。
    // ⚠️ tsc 侧声明见 `src/types/build-stamp.d.ts`（`tsc -noEmit` 在前，缺声明会挡构建）。
    define: {
        __REEL_BUILD__: JSON.stringify(new Date().toISOString()),
    },
    logLevel: 'info',
    sourcemap: prod ? false : 'inline',
    treeShaking: true,
    outfile: 'main.js',
})

if (prod) {
    await context.rebuild()
    process.exit(0)
} else {
    await context.watch()
}
