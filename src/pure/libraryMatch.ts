/**
 * 「库内检索」共用的**同名判定**（音频 / 书籍两处**同一份**，2026-10-01 #463）—— 纯逻辑，可单测。
 *
 * ## 为什么单独一层
 * 音频（`libraryAudio`）与书籍（`libraryBooks`）各有一套「在库内目录里找回同名文件」的匹配，
 * 两边都栽在同一个坑里：**只按相似度分数排序，同分时用路径字典序兜底**。
 * 用户报障现场（音频《七里香》）：正确的 `七里香.mp3` 与无关的 `兰亭序 - 周杰伦.mp3` **同为 74.7 分**，
 * 于是「填进框里的是哪一个」变成了路径字典序的**运气**。
 *
 * ⇒ 口径：**「文件名里有与目标标题完全同名的那段」是排序的第一关键字**，分数只是第二关键字
 *   （格式塔上「同名」是硬证据、「相似度高」是软证据 —— 硬的先于软的）。
 * ⚠️ ⛔ 别把它降级成「给分数加权重」：那还是要跟别的加分项比大小，同分现场照样分不出来。
 *
 * ⚠️ 归一化只服务**这个判定**（像 / 不像两档），⛔ 别拿它当打分用 —— 打分是另一套（`songSimilarityScore`）。
 */

/**
 * 归一匹配文本：小写、去掉空白与常见分隔/标点。
 * ⚠️ 保留中日韩字符与字母数字（`光辉岁月` / `emma` 各自保留）；⛔ 别顺手去掉其它语义字符。
 */
export function normalizeMatchText(s: string): string {
    return String(s ?? '')
        .toLowerCase()
        .replace(/[\s._\-—–·・、，,。．:：;；!！?？'"“”‘’`()（）\[\]【】{}<>《》]/g, '');
}

/**
 * 文件名拆出来的**两段**里，任一段与目标标题归一后相等 ⇒ true。
 *
 * 🔴 为什么要传两段、而不是传文件名：库内两种命名**混用** ——
 *    音频有 `歌手 - 歌名`（下载落盘形态）也有 `歌名 - 歌手`；书籍是 `书名 - 作者`。
 *    两个方向的「同名」都得认，⛔ 只认一侧会漏判（那正是这次报障现场的一半）。
 */
export function segmentsExactTitle(segA: string | undefined, segB: string | undefined, title: string): boolean {
    const t = normalizeMatchText(title);
    if (!t) return false;
    return normalizeMatchText(segA ?? '') === t || normalizeMatchText(segB ?? '') === t;
}
