/**
 * 条目右键菜单的「按场景隐藏项」口径 —— 纯数据，零依赖。
 *
 * 🔴 由来（2026-11-08 用户指令）：「播放器详情页的简介封面右键菜单不要显示观看、删除条目项」。
 *
 * 为什么要有这个模块而不是在 `.svelte` 里散写字符串：
 *   `hideItems` 的键同时被**组件模板**（决定 `{#if}`）和**视图层**（决定传什么）引用。
 *   写成裸字符串，两边改一处漏一处不会有任何报错；写成联合类型 + 常量，漏改直接 tsc 红。
 *
 * ⚠️ 这只是「少几项」，**不是**第二份菜单。菜单本体永远只有
 *   `views/components/EntryContextMenu.svelte` 那一份（文件头注释点名过两份必然漂移）。
 * ⛔ 别为此新增「详情页专用菜单组件」。
 */
export type EntryMenuHideKey =
    /** 主操作（观看 / 阅读 / 启动 / 播放） */
    | 'watch'
    /** 关联入口（常驻那条） */
    | 'associate'
    /** 编辑属性 */
    | 'edit'
    /** 添加摘抄 */
    | 'excerpt'
    /** 添加短评 */
    | 'comment'
    /** 添加攻略 */
    | 'guide'
    /** 记录重温 */
    | 'rewatch'
    /** 记录周目 */
    | 'playthrough'
    /** 记录时长 */
    | 'time'
    /** 删除条目 */
    | 'delete';

/**
 * 剧集页「简介封面」右键菜单要隐藏的项。
 *
 * 🔴 用户 2026-11-08 逐字：「播放器详情页的简介封面右键菜单不要显示观看、删除条目项」。
 *
 * 为什么这两项在这个场景该藏（而不是「顺手一起藏」）：
 *   · **观看**：用户人就在播放器详情页里，正在看的那一集就在左边播着
 *     ⇒ 「观看」这一项点下去要么重开一页、要么把当前播放打断，纯属自找麻烦。
 *   · **删除条目**：这是详情页，删掉当前条目等于把脚下这块地抽走
 *     （视图会随条目消失而失效）。危险操作留到**海报墙**上做，那里上下文清楚。
 *
 * ⚠️ 其余项（关联入口 / 编辑属性 / 摘抄 / 短评 / 攻略 / 重温 / 周目 / 时长）**全部保留**：
 *   用户只点名这两项，⛔ 不做「看起来更合理」的擅自扩展。
 */
export const EPISODE_COVER_MENU_HIDE: readonly EntryMenuHideKey[] = ['watch', 'delete'];
