/**
 * 编辑浮层「失焦自动保存」的**触发判据** ＋ 就地提示的**键空间**（纯逻辑，无 obsidian / 无 DOM，可单测）。
 *
 * 由来（用户 2026-10-08 两次点名，均为「触发条件」类需求）：
 *   · #568：「自动保存触发条件仅为填写了正确前置路径，**为空时不触发自动保存**」；
 *   · #569：「**仅选中框不填入为空值不触发保存**」「**拉取网络路径填入后自动保存**，而不是需要你
 *     手动切换其他框才保存」「填写了的链接路径**仅再次选中而不修改不触发保存**」。
 *   · #583（2026-10-09）：「书籍类型…的自动保存逻辑与影视类型不一致，请说明并统一」＋「其他类型也一并统一」
 *     ⇒ 判据从「集浮层专用」（旧文件名 `epAutoSave`）升为**四类浮层共用**：集 / 游戏 / 音乐 / 书籍。
 *     ⛔ 别在组件里再写一遍条件 —— 四条规则只此一处。
 *
 * ⇒ 三条口径收成一个判据（**顺序不可换**）：
 *   ⑴ 去空白后为空 ⇒ 永不保存（空值优先于 `force`：程序也不许把空值当「填入」存下去）；
 *   ⑵ `force`（程序填入：粘贴 / 候选回填 / 本地检索 / 浏览选文件）⇒ **立即保存**，不等失焦；
 *   ⑶ 否则**只有真的改了才保存** —— 与「表单态里已存的那份值」比对（⛔ 别另存一份「上次的值」，
 *      两份状态必然漂移：打开/关闭浮层、批量填入都会改表单态）。
 *
 * ⚠️ 比对一律**先 trim**：`'a'` 与 `' a '` 视为没改（提交侧写回时也是 `.trim() || undefined`，
 *    所以两份的空白差异本来就会被抹平 —— 若这里不 trim，就会出现「值其实没变却弹了一条已保存」）。
 */

/**
 * 这一个字段此刻**该不该**自动保存。
 * @param next      输入框当前的值（缓冲）
 * @param committed 表单态里**已存**的那份值（同一字段、同一集）
 * @param force     程序填入（粘贴 / 回填 / 选文件）时传 `true` —— 跳过⑶ 那条比对
 */
export function shouldAutoSave(next: string, committed: string, force = false): boolean {
    const v = next.trim();
    if (!v) return false;                    // ⑴ 空值永不保存
    if (force) return true;                  // ⑵ 程序填入 ⇒ 立即保存
    return v !== committed.trim();           // ⑶ 没改不保存
}

/**
 * 🔴 #583 「就地提示」的**键空间** —— 提示要落在**哪一行的标签旁**，由这个键决定。
 *
 * 为什么要有它：四类浮层共用**一个**提示状态机（`savedKey` / `savedBad` / `savedSeq`），
 * 视图模板靠 `savedKey === '…'` 决定哪一行出提示。⛔ 别在组件里手写裸字符串 ——
 * 键名拼错是**静默**的（提示照样弹，只是落在别处或哪都不落），拼错一处就会长期看不出来。
 *
 * 命名 = `<浮层>:<字段>`（一个浮层有多个字段时靠后缀区分）。
 */
export const AUTOSAVE_KEYS = {
    /** 影视·集浮层：集标题 */
    epTitle: 'ep:title',
    /** 影视·集浮层：网络地址 */
    epUrl: 'ep:url',
    /** 影视·集浮层：本地路径 */
    epLocal: 'ep:local',
    /** 游戏浮层：启动路径（.lnk） */
    gameLaunch: 'game:launch',
    /** 游戏浮层：网络路径 */
    gameUrl: 'game:url',
    /** 音乐浮层：文件路径 */
    audioPath: 'audio:path',
    /** 音乐浮层：网络地址（#601 新增字段） */
    audioUrl: 'audio:url',
    /** 书籍浮层：文件路径 */
    bookPath: 'book:path',
    /** 书籍浮层：网络地址（在线阅读链接） */
    bookUrl: 'book:url',
} as const;

/** 就地提示的键（取值域 = 上面那张表） */
export type AutoSaveKey = (typeof AUTOSAVE_KEYS)[keyof typeof AUTOSAVE_KEYS];

/** 键的**全集**（顺序 = 浮层在表单里的出现顺序）—— 给「键空间没写错」这类断言用 */
export const AUTOSAVE_KEY_VALUES: readonly AutoSaveKey[] = Object.values(AUTOSAVE_KEYS);

