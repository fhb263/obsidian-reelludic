// 主视图导航布局（#541）：横向页签 / 纵向页签 / 聚合下拉（三档平级）。
//   ⚠️ #574：文案去掉方位限定词（详见 `NAV_LAYOUT_LABELS` 上方注释）；2026-11-15 m07364 按形态重命名。
//
// 🔴 为什么抽纯模块：布局 id 同时被三处消费 —— 设置页下拉、`HomeView.svelte` 的结构分支
//    （要增删 DOM 节点，⛔ 不能只靠 CSS 变量）、`main.ts` 的实时重推。id 写错一处就是「切了没反应」。
//
// ⚠️ 它**不是** `uiTheme`（native / modern）的子集：`uiTheme` 管的是顶部胶囊**长什么样**（下划线 vs 描边指示器），
//    本模块管的是**排在哪**。两者正交，⛔ 别互相推导。
//
// ⚠️ id `'sidebar'` 是**存量数据里的值**（旧 data.json 存过它）⇒ append-only，⛔ 别跟着改名的文案一起改
//    （改 id = 老用户升级后回落到 `top`，等于悄悄换脸）。用户可见的名字只走 `NAV_LAYOUT_LABELS`。

/** 主导航布局 */
export type NavLayout = 'top' | 'sidebar' | 'merged';

/** 合法值（顺序 = 卡片式勾选里的展示顺序；默认项在最前） */
export const NAV_LAYOUTS: readonly NavLayout[] = ['top', 'sidebar', 'merged'];

/** 卡片文案（用户可见；与设置项 desc 同一条「准确·简洁」口径）。
 *  🔴 `sidebar` 这一档的名字**先后改过五次**（方位词从「左侧」一路改到「右上角」，再到 #574 的**无方位词**，
 *     再到 2026-11-15 m07364 的**按形态命名**）——
 *     改名时**只动这里**，`id` 不动；文案必须描述**现在**的形态（写「左侧」会让用户在下拉里找不到它）。
 *     ⚠️ #574 去掉方位限定词：同一档在不同宽度下的落点并不恒定（窄屏会退成别的排布），
 *       用户要的是**三档并列可读**，方位词反而是噪音。
 *       ⛔ 本注释**刻意不抄**历史文案的字面量 —— 注释会进产物，抄了就自撞 #574 那条反向守卫。
 *  🔴 2026-11-15 m07364 用户逐字：「基本设置导航布局的顶部胶囊、文字菜单、合并视图名称改成
 *     "横向页签、纵向页签、聚合下拉"视图」。⇒ 三档一律改成**形态名**：
 *        `top` → 横向页签（一排横着排的页签，iOS 分段控制器形态）
 *        `sidebar` → 纵向页签（点开是一列竖着排的页签，幽灵风）
 *        `merged` → 聚合下拉（没有页签栏，靠顶端的媒体类型/状态/排序三个下拉聚合导航）
 *     ⚠️ 「横向页签 / 纵向页签」描述的是**页签自己的排列方向**，不是它贴在屏幕哪一边 ——
 *       这正是 #574 想去掉的方位噪音的反面：方向是形态本身，位置才是随宽度变的。
 *  🔴 `merged`（#547）：**取消顶部的分类页签**，改由顶端一行筛选栏（媒体类型 / 状态 / 排序）导航，
 *     追更与统计降为右端两枚图标按钮。id 取 `merged`（合并视图）—— 这是这一档最初的名字，
 *     m07364 起对外文案改叫「聚合下拉」，id 保持不变（存量数据）。 */
export const NAV_LAYOUT_LABELS: Record<NavLayout, string> = {
    top: '横向页签',
    sidebar: '纵向页签',
    merged: '聚合下拉',
};

/**
 * 归一：未知值一律回 **`top`**（= 1.2.0 及以前的形态）——
 * 缺省值必须是「与旧版观感一致」的那一个，⛔ 不能回退成文字菜单 / 合并视图（升级即换脸）。
 *
 * ⚠️ 这里的「缺省」只覆盖**存量数据读出来是脏值**这一种情况。
 *    手机端首次安装的**播种**不在这里做 —— 见 `defaultNavLayoutFor(isMobile)`，
 *    以及 `main.ts` 里 `Object.assign({}, DEFAULT_SETTINGS, rawSettings)` 之后那段。
 */
export function normalizeNavLayout(raw: unknown): NavLayout {
    return raw === 'sidebar' || raw === 'merged' ? raw : 'top';
}

/**
 * 首次安装时该给哪一档（用户 m05673：「默认导航布局应该为合并视图以适应手机端竖屏显示」）。
 *
 * 🔴 为什么必须单独一个函数、而不是改 `normalizeNavLayout` 的兜底：
 *    `normalizeNavLayout` 是**读存量数据**的归一器，它的 `top` 兜底保护的是老用户
 *    （改它 = 全体老用户升级即换脸）。而这条只作用于**从没存过设置的新装环境**，
 *    两者判据完全不同，⛔ 别合并。
 *
 * 阈值取「是不是移动端」而不是屏幕宽度：桌面窄窗口用户是**故意**把窗口拖窄的，
 * 不该被强制换布局；手机/平板天生竖屏，合并视图才是那套结构（`HomeView` 的 merged 分支）。
 */
export function defaultNavLayoutFor(isMobile: boolean): NavLayout {
    return isMobile ? 'merged' : 'top';
}

