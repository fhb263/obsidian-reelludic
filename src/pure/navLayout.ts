//   ⚠️ #574：文案去掉方位限定词（详见 `NAV_LAYOUT_LABELS` 上方注释），本行随之改。
//
// 🔴 为什么抽纯模块：布局 id 同时被三处消费 —— 设置页下拉、`HomeView.svelte` 的结构分支
//    （要增删 DOM 节点，⛔ 不能只靠 CSS 变量）、`main.ts` 的实时重推。id 写错一处就是「切了没反应」。
//
// ⚠️ 它**不是** `uiTheme`（native / modern）的子集：`uiTheme` 管的是顶部胶囊**长什么样**（下划线 vs 描边指示器），
//    本模块管的是**排在哪**。两者正交，⛔ 别互相推导。
//
// ⚠️ id `'sidebar'` 是**存量数据里的值**（旧 data.json 存过它）⇒ append-only，⛔ 别跟着改名的文案一起改
//    （改 id = 老用户升级后回落到 `top`，等于悄悄换脸）。用户可见的名字只走 `NAV_LAYOUT_LABELS`。

/** 主导航布局 */
export type NavLayout = 'top' | 'sidebar' | 'merged';

/** 合法值（顺序 = 卡片式勾选里的展示顺序；默认项在最前） */
export const NAV_LAYOUTS: readonly NavLayout[] = ['top', 'sidebar', 'merged'];

/** 卡片文案（用户可见；与设置项 desc 同一条「准确·简洁」口径）。
 *  🔴 `sidebar` 这一档的名字**先后改过四次**（方位词从「左侧」一路改到「右上角」，再到本批的**无方位词**）——
 *     改名时**只动这里**，`id` 不动；文案必须描述**现在**的形态（写「左侧」会让用户在下拉里找不到它）。
 *     ⚠️ #574 去掉方位限定词：同一档在不同宽度下的落点并不恒定（窄屏会退成别的排布），
 *       用户要的是**三档并列可读**（顶部胶囊 / 文字菜单 / 合并视图），方位词反而是噪音。
 *       ⛔ 本注释**刻意不抄**历史文案的字面量 —— 注释会进产物，抄了就自撞 #574 那条反向守卫。
 *  🔴 `merged`（#547）：**取消顶部的分类页签**，改由顶端一行筛选栏（媒体类型 / 状态 / 排序）导航，
 *     追更与统计降为右端两枚图标按钮。id 取 `merged`（合并视图）—— 这也是用户给这一档起的名字。 */
export const NAV_LAYOUT_LABELS: Record<NavLayout, string> = {
    top: '顶部胶囊',
    sidebar: '文字菜单',
    merged: '合并视图',
};

/**
 * 归一：未知值一律回 **`top`**（= 1.2.0 及以前的形态）——
 * 缺省值必须是「与旧版观感一致」的那一个，⛔ 不能回退成文字菜单 / 合并视图（升级即换脸）。
 */
export function normalizeNavLayout(raw: unknown): NavLayout {
    return raw === 'sidebar' || raw === 'merged' ? raw : 'top';
}

