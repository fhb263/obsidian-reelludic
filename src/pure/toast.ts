/** 自动保存成功 */
export const TOAST_SAVED = '设置已保存';

/** 自动保存失败（网络错误 / 路径冲突等） */
export const TOAST_FAILED = '保存失败，请重试';

/** 停留时长（毫秒）—— 🔴 #593 用户给定 **1.5 秒**（原 3000） */
export const TOAST_MS = 1500;

/**
 * 🔴 #593 轻提示**该不该重新弹**的判据（`EntryForm` 的就地提示与快捷关联弹窗共用这一处）。
 *
 * · 提示**正在显示**（`visible`）时的成功保存 ⇒ **不重弹**（防「高频操作闪烁」）；
 * · ⚠️ **失败态例外**：报错必须看得见，⛔ 不能因为「防闪烁」把红字吞掉（成功提示还在时又来一条失败，
 *   直接换成失败态）。
 * · 提示**已经消失** ⇒ 照常弹（这就是用户说的「1.5 秒后再次操作才重新弹出」）。
 */
export function shouldFlashSaved(visible: boolean, bad: boolean): boolean {
    return !visible || bad;
}
