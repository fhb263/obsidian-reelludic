/**
 * 书名基名：`书名 - 作者`（缺作者只留书名；两者都缺 ⇒ 空串，由净化层回落到「未命名」）。
 * 🔴 这是「书名在前、作者在后」的**唯一定义处** —— `pure/libraryBooks.splitBookStem` 按它反向切，
 *    两处口径必须一致（⚠️ 与音频的「艺人 - 歌名」**顺序相反**，⛔ 别照抄）。
 */
export function bookStem(title: string, author: string | undefined): string {
    const t = String(title ?? '').trim();
    const a = String(author ?? '').trim();
    return a && t ? `${t} - ${a}` : t || a;
}
