// 「关于 › 更新日志」弹窗的正文 —— **一个版本一句话**（#492 起 = **手写常量表**）。
//
// 由来（用户 2026-10-03）：「更新日志按钮功能的弹窗内容改成按
//   https://github.com/fhb263/obsidian-reelludic/releases#release-1.1.0 这一系列的一句话来写」。
//   ⇒ #491 那套「把本版 CHANGELOG 的**整节**（600+ 行）嵌进产物」的做法**整体退场**：
//     弹窗只列**每个版本一句话**（最新在上），想看细节的走底部那枚链接去看完整发布记录。
//
// 🔴 为什么从「生成物」改回「手写」：一句话的措辞是**编辑**出来的，机器没有可靠的源可摘
//    （`RELEASE-NOTES-*.md` 的引言长短不一、还只覆盖一部分版本）⇒ 手写 + **一条漂移守卫**：
//    版本号与日期必须与用户向 `CHANGELOG.md` 的 `## [x] - yyyy-mm-dd` 标题**逐字一致**
//    （断言脚本会逐条核对）。⚠️ 所以改 CHANGELOG 的日期时，记得同步这里。
//
// ⚠️ 数据来源 = 上面那个 releases 页的各版说明 + 本仓根目录的 `RELEASE-NOTES-<版本>.md`（用户向）。
// ⚠️ 一律**最新在前**（`RELEASE_NOTES[0]` = 当前版本）；⛔ 不要为了「按版本号排序」在渲染端再 sort。
//
// 🔴🔴 **改本文件前先读**（#491 实测踩出来的）：这里的正文是**中文散文**，而 esbuild 默认把非 ASCII
//    转义成 `\uXXXX`、断言脚本又会 decode 回中文 ⇒ 正文里的每个短语都会出现在「产物」里。
//    若某短语恰好与全仓那些「某短语在产物里出现 N 次」的**产物级断言**撞上，就会**假红**。
//    ⇒ 改文案（或加新版本行）后**必须重跑断言脚本**；已知里数条守卫就是这么红的。

/** 一个版本的一句话说明 */
